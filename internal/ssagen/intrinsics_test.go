package ssagen

import (
	"fmt"
	"strings"
	"testing"

	"go-backend-ssa/internal/ir"
	"go-backend-ssa/internal/ssa"
	"go-backend-ssa/internal/types"
)

func TestNativeIntrinsicBodiesAndSIMDIsolation(t *testing.T) {
	for _, arch := range []string{"386", "amd64", "arm64", "wasm"} {
		t.Run(arch, func(t *testing.T) {
			t.Parallel()
			c := buildContext(arch)
			g, u := c.Typecheck.IR, c.Typecheck.IR.Types
			simdSym := u.NewPkg("simd/archsimd", "archsimd").Lookup("Int32x4.Add")
			if c.IsIntrinsicSym(simdSym) {
				t.Fatal("SIMD intrinsic enabled without experiment")
			}
			u.Experiment.SIMD = true
			c.InitTables()
			// Initialize an unrelated configuration while retaining the first builders.
			other := buildContext("amd64")
			if other.IsIntrinsicSym(other.Typecheck.IR.Types.NewPkg("simd/archsimd", "archsimd").Lookup("Int32x4.Add")) {
				t.Fatal("experiment leaked between contexts")
			}
			builder := c.intrinsics[intrinsicKey{c.Arch.LinkArch.Arch, "simd/archsimd", "Int32x4.Add"}]
			if (builder != nil) != (arch != "386") {
				t.Fatal("unexpected target SIMD gate")
			}
			if builder != nil {
				f, fn, _ := frameGraph(c, "simd")
				s := &state{compilation: c, f: f, config: c.ssaConfig, curfn: fn}
				s.startBlock(f.Entry)
				s.pushLine(fn.Pos())
				a := f.Entry.NewValue0(fn.Pos(), ssa.OpZeroSIMD, u.TypeVec128)
				b := f.Entry.NewValue0(fn.Pos(), ssa.OpZeroSIMD, u.TypeVec128)
				call := g.NewCallExpr(fn.Pos(), ir.OCALLFUNC, fn.Nname, nil)
				call.SetType(u.TypeVec128)
				v := builder(s, call, []*ssa.Value{a, b})
				if v.Op != ssa.OpAddInt32x4 || v.Type != u.TypeVec128 || v.Args[0] != a || v.Args[1] != b {
					t.Fatal("intrinsic builder lost target/type/argument identity", v)
				}
			}
			u.Experiment.SIMD = false
			c.InitTables()
			for _, probe := range []struct {
				pkg, name     string
				args, results []*types.Type
			}{
				{"internal/runtime/sys", "GetCallerPC", nil, []*types.Type{u.Types[types.TUINTPTR]}},
				{"math/bits", "TrailingZeros64", []*types.Type{u.Types[types.TUINT64]}, []*types.Type{u.Types[types.TINT]}},
			} {
				sym := u.NewPkg(probe.pkg, "probe").Lookup(probe.name)
				if !c.IsIntrinsicSym(sym) {
					continue
				}
				fields := func(ts []*types.Type) []*types.Field {
					var fs []*types.Field
					for i, typ := range ts {
						fs = append(fs, u.NewField(u.AutogeneratedPos, u.LocalPkg.Lookup(fmt.Sprintf("p%d", i)), typ))
					}
					return fs
				}
				fn := g.NewFunc(u.AutogeneratedPos, u.AutogeneratedPos, sym, u.NewSignature(nil, fields(probe.args), fields(probe.results)))
				fn.DeclareParams(true)
				g.InitLSym(fn, true)
				c.GenIntrinsicBody(fn)
				if g.CurFunc != nil || len(fn.Body) != 1 {
					t.Fatal("intrinsic body generation state")
				}
				call := fn.Body[0].(*ir.ReturnStmt).Results[0].(*ir.CallExpr)
				if !call.Walked() || call.Typecheck() != 1 || !g.IsIntrinsicCall(call) {
					t.Fatal("generated body is not a native walked intrinsic call")
				}
				compiled := c.BuildSSA(fn, 0, false)
				if compiled.RegAlloc == nil || strings.Contains(compiled.String(), "StaticCall") {
					t.Fatal("intrinsic failed to lower", compiled)
				}
				g.CurFunc = nil
			}
		})
	}
}
