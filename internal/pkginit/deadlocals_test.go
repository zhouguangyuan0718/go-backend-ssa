const deadSource = `package p
var Global int
func Dead(p int){p=1}
func Chain(p,q int){p=q;q=3}
func Used(p,q int)int{p=q;q=3;return p}
func Intentional(p int){p=1;_=p}
func AllBlank(p,q int){p=1;q=2;_,_=p,q}
func Mixed(p,q int){p=1;_,q=p,2}
func Effect(p int,f func()int){p=f()}
func Store(p int){Global=p}
func Result()(r int){r=3;return}
func Captured(p int)func()int{p=1;return func()int{return p}}
func Discard(p func(),q int){p=func(){Global=q}}
func Nil(p *int){p=nil}
func Definition(p func()){x:=1;p=func(){_=x}}
`

type deadInput struct {
	*deadlocals.Context
	target *ir.Package
}

func deadContext(t *testing.T) *deadInput {
	t.Helper()
	c := sourceContext(t, "example/p", deadSource, false)
	c.MakeTask()
	ssagen.NewContext(c.Noder.Typecheck).NewSymABIs().GenABIWrappers()
	return &deadInput{deadlocals.NewContext(c.Noder.Typecheck.IR), c.Noder.Typecheck.Target}
}

func deadFunc(c *deadInput, name string) *ir.Func {
	for _, fn := range c.target.Funcs {
		if fn.Sym().Name == name {
			return fn
		}
	}
	panic("missing function " + name)
}

func TestNativeDeadLocals(t *testing.T) {
	c := deadContext(t)
	discard := deadFunc(c, "Discard").Body[0].(*ir.AssignStmt)
	closure := discard.Y.(*ir.ClosureExpr).Func
	if closure.LSym != nil {
		t.Fatal("discarded closure already has text symbol")
	}
	var local *ir.Name
	for _, n := range deadFunc(c, "Definition").Dcl {
		if n.Sym().Name == "x" {
			local = n
		}
	}
	if local == nil || local.Defn == nil {
		t.Fatal("missing initial local definition")
	}
	c.Funcs(c.target.Funcs)
	if local.Defn != nil {
		t.Fatal("discarded local retains stale definition")
	}
	for name, want := range map[string]int{"Dead": 1, "Chain": 2, "Used": 0, "Intentional": 0, "AllBlank": 0, "Mixed": 3, "Effect": 0, "Store": 0, "Result": 0, "Captured": 0, "Discard": 1, "Nil": 1, "Definition": 2} {
		fn := deadFunc(c, name)
		got := 0
		check := func(lhs, rhs ir.Node) {
			if lhs == c.IR.BlankNode && rhs != nil && rhs.Op() == ir.OLITERAL && c.IR.Int64Val(rhs) == 0 {
				got++
				if !c.IR.OwnsNode(rhs) || rhs.Type() != c.IR.Types.Types[types.TINT] || rhs.Pos() != c.IR.Types.AutogeneratedPos {
					t.Fatal("replacement zero lost its graph, type, or position")
				}
			}
		}
		ir.Visit(fn, func(n ir.Node) {
			switch n := n.(type) {
			case *ir.AssignStmt:
				check(n.X, n.Y)
			case *ir.AssignListStmt:
				if n.Op() == ir.OAS2 {
					for i := range n.Lhs {
						check(n.Lhs[i], n.Rhs[i])
					}
				}
			}
		})
		if got != want {
			t.Errorf("%s: got %d discarded assignments, want %d; body %v", name, got, want, fn.Body)
		}
	}
	if closure.LSym == nil || closure.LSym.Func() == nil {
		t.Fatal("discarded closure missing native function info")
	}
	if c.IR.CurFunc != nil {
		t.Fatal("current function leaked")
	}
}

func deadDump(c *deadInput) string {
	var out bytes.Buffer
	for _, fn := range c.target.Funcs {
		ir.FDump(&out, "snapshot", fn)
	}
	return out.String()
}

func TestNativeDeadLocalsDisabled(t *testing.T) {
	for _, flag := range []string{"N", "NoDeadLocals"} {
		t.Run(flag, func(t *testing.T) {
			c := deadContext(t)
			before := deadDump(c)
			if flag == "N" {
				c.IR.Base.Flag.N = 1
			} else {
				c.IR.Debug.NoDeadLocals = 1
			}
			c.Funcs(c.target.Funcs)
			if before != deadDump(c) {
				t.Fatal("disabled pass changed IR")
			}
		})
	}
}

func TestNativeDeadLocalsIsolation(t *testing.T) {
	old := deadContext(t)
	old.Funcs(old.target.Funcs)
	before := deadDump(old)
	for i := 0; i < 8; i++ {
		t.Run(fmt.Sprint(i), func(t *testing.T) {
			t.Parallel()
			c := deadContext(t)
			var trace bytes.Buffer
			c.IR.TraceWriter = &trace
			c.IR.Debug.AstDump = "~."
			c.Funcs(c.target.Funcs)
			if before != deadDump(old) || c.IR.BlankNode == old.IR.BlankNode || !strings.Contains(trace.String(), "deadLocals") || !strings.Contains(trace.String(), "deadlocals closure skipped") {
				t.Fatal("retained graph or instance trace failed")
			}
		})
	}
}

func TestNativeDeadLocalsRejectsForeignFuncs(t *testing.T) {
	a, b := deadContext(t), deadContext(t)
	before := deadDump(a)
	defer func() {
		if recover() == nil {
			t.Error("foreign function accepted")
		}
		if before != deadDump(a) {
			t.Error("mutated local graph before rejecting foreign input")
		}
	}()
	fns := append([]*ir.Func(nil), a.target.Funcs...)
	a.Funcs(append(fns, b.target.Funcs[0]))
}
