// Library-owned compilation state. Compiler object definitions and algorithms
// are generated from upstream; no placeholder Type, Sym or linker symbol is used.
package types

import (
	"fmt"
	"go-backend-ssa/diagnostic"
	"go-backend-ssa/internal/base"
	"go-backend-ssa/internal/cmd/obj"
	"go-backend-ssa/internal/cmd/src"
	"go-backend-ssa/internal/go/buildcfg"
	"go-backend-ssa/internal/go/types/errors"
	"go/constant"
	"strconv"
	"sync"
)

// Universe owns one compilation's mutable type and package graph. Its zero value
// is invalid. Except for InternString, calls within a Universe are serialized.
type Universe struct {
	links                     *base.LinkContext
	initialized               bool
	ComparableType, recvType  *Type
	ShapePkg                  *Pkg
	IsInt, IsFloat, IsComplex [NTYPE]bool
	AutogeneratedPos          src.XPos
	basicTypes                [14]struct {
		name  string
		etype Kind
	}
	typedefs [3]struct {
		name                      string
		etype, sameas32, sameas64 Kind
	}
	mu               sync.Mutex
	strings          map[string]string
	packages         map[string]*Pkg
	anonymous        *Pkg
	ptrSize, regSize int
	maxWidth         int64
	// Upstream SSA singleton names are retained as per-compilation fields.
	// Treat these bindings as read-only after construction, like the upstream
	// globals; Type flags still belong to this Universe and may be mutated.
	TypeInvalid, TypeMem, TypeFlags, TypeVoid                                         *Type
	TypeInt128, TypeVec128, TypeVec256, TypeVec512, TypeMask                          *Type
	TypeResultMem                                                                     *Type
	UntypedString, UntypedBool, UntypedInt, UntypedRune, UntypedFloat, UntypedComplex *Type
	UntypedTypes                                                                      [constant.Complex + 1]*Type
	DefaultKinds                                                                      [constant.Complex + 1]Kind
	NewPtrCacheEnabled                                                                bool
	scalars                                                                           [NTYPE]*Type
	Types                                                                             [NTYPE]*Type
	ByteType, RuneType, AnyType, ErrorType                                            *Type
	SimType                                                                           [NTYPE]Kind
	algPriority                                                                       [ASPECIAL + 1]int8
	SlicePtrOffset, SliceLenOffset, SliceCapOffset, SliceSize, StringSize             int64
	SkipSizeForTracing, CalcSizeDisabled                                              bool
	defercalc                                                                         int
	deferredTypeStack                                                                 []*Type
	Pos                                                                               src.XPos
	PosTable                                                                          src.PosTable
	Experiment                                                                        buildcfg.ExperimentFlags
	Diagnostics                                                                       diagnostic.Collector
	BuiltinPkg, LocalPkg, UnsafePkg                                                   *Pkg
	BlankSym                                                                          *Sym
	NumImport                                                                         map[string]int
	BasicTypeNames                                                                    []string
	fmtBufferPool                                                                     sync.Pool
}

func NewUniverse(ptrSize, regSize int, maxWidth int64) *Universe {
	if (ptrSize != 4 && ptrSize != 8) || regSize != ptrSize || maxWidth <= 0 {
		panic("invalid target layout")
	}
	u := newUniverse()
	u.ptrSize, u.regSize, u.maxWidth = ptrSize, regSize, maxWidth
	u.BuiltinPkg = u.NewPkg("go.builtin", "")
	u.UnsafePkg = u.NewPkg("unsafe", "unsafe")
	u.LocalPkg = u.anonymous
	u.BlankSym = u.BuiltinPkg.Lookup("_")
	u.AutogeneratedPos = u.PosTable.XPos(src.MakePos(src.NewFileBase("<autogenerated>", "<autogenerated>"), 1, 0))
	return u
}
func (u *Universe) PointerSize() int  { return u.ptrSize }
func (u *Universe) RegisterSize() int { return u.regSize }
func (u *Universe) MaxWidth() int64   { return u.maxWidth }

// Scalar returns the canonical builtin after InitTypes. Before initialization
// it returns an interned unnamed node for construction-only use; such use prevents
// later InitTypes from replacing its identity.
func (u *Universe) Scalar(kind Kind) (*Type, error) {
	if u == nil || u.ptrSize == 0 {
		return nil, fmt.Errorf("uninitialized Universe")
	}
	if !(kind >= TINT8 && kind <= TBOOL || kind == TSTRING || kind == TUNSAFEPTR) {
		return nil, fmt.Errorf("not a supported scalar kind: %d", kind)
	}
	if t := u.Types[kind]; t != nil {
		return t, nil
	}
	if t := u.scalars[kind]; t != nil {
		return t, nil
	}
	t := u.newType(kind)
	u.scalars[kind] = t
	return t, nil
}

func (t *Type) Universe() *Universe {
	if t == nil {
		return nil
	}
	return t.universe
}
func (p *Pkg) Universe() *Universe {
	if p == nil {
		return nil
	}
	return p.universe
}
func (s *Sym) Universe() *Universe {
	if s == nil {
		return nil
	}
	return s.Pkg.Universe()
}
func (t *Type) TupleTypes() (*Type, *Type, error) {
	if t == nil || t.kind != TTUPLE {
		return nil, nil, fmt.Errorf("not a tuple")
	}
	pair := t.extra.(*Tuple)
	return pair.first, pair.second, nil
}

// Lookup explicitly supplies the owner for the upstream nil-package case.
func (u *Universe) Lookup(pkg *Pkg, name string) (*Sym, error) {
	if u == nil || u.ptrSize == 0 {
		return nil, fmt.Errorf("uninitialized Universe")
	}
	if pkg == nil {
		pkg = u.anonymous
	}
	if pkg.universe != u {
		return nil, fmt.Errorf("package belongs to another Universe")
	}
	return pkg.Lookup(name), nil
}

// A violated compiler invariant aborts this call, never the embedding process.
// This binds the original base.Fatalf signature; it is not a source diagnostic.
func (u *Universe) fatalf(format string, args ...any) { panic(fmt.Errorf(format, args...)) }

// Fields retain the upstream representation: ownership comes from Type and Sym,
// without a second owner field or a wrapper around the native Field object.
func (u *Universe) checkNewField(pos src.XPos, sym *Sym, typ *Type) {
	if typ == nil || typ.universe != u {
		panic("field type belongs to another or uninitialized compilation")
	}
	if sym != nil && sym.Universe() != u {
		panic("field symbol belongs to another or uninitialized compilation")
	}
}

func (u *Universe) checkFields(fields []*Field) {
	for _, field := range fields {
		if field == nil {
			panic("nil field")
		}
		u.checkNewField(field.Pos, field.Sym, field.Type)
	}
}

func (u *Universe) checkSignature(recv *Field, params, results []*Field) {
	if recv != nil {
		u.checkNewField(recv.Pos, recv.Sym, recv.Type)
	}
	u.checkFields(params)
	u.checkFields(results)
}

func (u *Universe) assertf(b bool, format string, args ...any) {
	if !b {
		u.fatalf(format, args...)
	}
}
func (u *Universe) errorf(format string, args ...any) { u.errorfAt(u.Pos, 0, format, args...) }
func (u *Universe) errorfAt(pos src.XPos, code errors.Code, format string, args ...any) {
	u.Diagnostics.Add(diagnostic.Error, strconv.Itoa(int(code)), u.PosTable.Pos(pos), fmt.Sprintf(format, args...))
}
func (u *Universe) checkMethods(methods []*Field) {
	for _, f := range methods {
		if f == nil {
			panic("nil method field")
		}
		if f.Type != nil && f.Type.universe != u {
			panic("method type belongs to another compilation")
		}
		if f.Sym != nil && f.Sym.Universe() != u {
			panic("method symbol belongs to another compilation")
		}
	}
}

// Initialization precedes graph construction. The host supplies its actual type
// name objects (ir.Name in the compiler), as required by upstream InitTypes.
func (u *Universe) checkInitTypes(defTypeName func(*Sym, *Type) Object) {
	if u.initialized || defTypeName == nil {
		panic("InitTypes requires a fresh Universe and type-name callback")
	}
	for _, t := range u.scalars {
		if t != nil {
			panic("InitTypes must precede Scalar")
		}
	}
	u.initialized = true
}
func (u *Universe) checkNamed(obj Object) {
	if obj == nil || obj.Sym() == nil || obj.Sym().Universe() != u {
		panic("type name belongs to another or uninitialized compilation")
	}
}

// BindLink binds the compiler symbol namespace once. Existing symbols must not
// be reinterpreted in another Link; independent compilations need a new Universe.
func (u *Universe) BindLink(link *obj.Link) {
	if u == nil || link == nil {
		panic("symbol binding requires Universe and Link")
	}
	if u.links != nil {
		if u.links.Ctxt != link {
			panic("Universe already bound to another Link")
		}
		return
	}
	u.links = base.NewLinkContext(link)
}
func symbolUniverse(sym *Sym) *Universe {
	u := sym.Universe()
	if u == nil || u.links == nil {
		panic("symbol has no bound compiler Link")
	}
	return u
}

// LinkContext returns the explicitly bound native compiler symbol inputs.
func (u *Universe) LinkContext() *base.LinkContext { return u.links }
