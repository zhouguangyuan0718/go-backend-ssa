package port

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"strings"
)

// Alias the checked migrated constants, preserving their native named types,
// untyped constant semantics, and iota-derived identities. The facade never
// duplicates numeric values or maintains a separate list of opcode names.
func renderConstantFacades(r *Rendered, p Plan, imports map[string]string, after *packageImporter) error {
	sources := map[string]Provenance{}
	for _, source := range r.Ledger.Files {
		sources[source.Output] = source
	}
	fs := token.NewFileSet()
	packages := map[string][]*ast.File{}
	for _, u := range p.Units {
		if !u.ExportConstants {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), u.output(), r.Files[u.output()], 0)
		if err != nil {
			return err
		}
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by %s from %s; DO NOT EDIT.\n\npackage %s\n\nimport compiler %q\n\nconst (\n", ToolVersion, u.Source, f.Name.Name, imports[u.sourcePackage()])
		count := 0
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.CONST {
				continue
			}
			for _, spec := range g.Specs {
				for _, name := range spec.(*ast.ValueSpec).Names {
					if name.IsExported() {
						fmt.Fprintf(&b, "%s = compiler.%s\n", name.Name, name.Name)
						count++
					}
				}
			}
		}
		if count == 0 {
			return fmt.Errorf("no exported constants in %s", u.Source)
		}
		b.WriteString(")\n")
		data, err := format.Source([]byte(b.String()))
		if err != nil {
			return err
		}
		output := u.constantsOutput()
		if _, exists := r.Files[output]; exists {
			return fmt.Errorf("constant facade output collision: %s", output)
		}
		facade, err := parser.ParseFile(fs, output, data, 0)
		if err != nil {
			return err
		}
		packages[path.Dir(output)] = append(packages[path.Dir(output)], facade)
		r.Files[output] = data
		source, ok := sources[u.output()]
		if !ok {
			return fmt.Errorf("constant facade missing native provenance: %s", u.Source)
		}
		r.Ledger.Files = append(r.Ledger.Files, Provenance{Output: output, Source: u.Source, SourceSHA256: source.SourceSHA256, OutputSHA256: hash(data), Rule: "public-constant-aliases-v1", Declarations: []string{"exported constants"}})
	}
	for _, dir := range sortedKeys(packages) {
		// All dependencies are already migrated. This verifies alias references and
		// collisions between generated facade files before installation.
		pkg, info, err := checkTypes(fs, "go-backend-ssa/"+dir, packages[dir], after)
		if err != nil {
			return fmt.Errorf("constant facade %s: %w", dir, err)
		}
		if err := auditOutput(pkg, packages[dir], info); err != nil {
			return err
		}
	}
	return nil
}
