package port

func reflectAlgorithms(context *ContextRule) Unit {
	u := Unit{Source: "src/cmd/compile/internal/reflectdata/alg.go", WholeFile: true, Context: context,
		// The signature builder is local scratch storage, not an owned graph node.
		// Only its stateful private operation receives the existing context.
		ContextParams: []string{"eqSigBuilder.build"},
		Checks:        map[string]string{"EqFor": "checkType", "genhash": "checkType", "geneq": "checkType", "eqSignature": "checkType"},
		State: []StateRule{
			{Source: "src/cmd/compile/internal/base/flag.go", Variable: "Flag", Field: "Typecheck.IR.Base.Flag"},
			{Source: "src/cmd/compile/internal/base/print.go", Variable: "AutogeneratedPos", Field: "Typecheck.IR.Types.AutogeneratedPos"},
			{Source: "src/cmd/compile/internal/ir/func.go", Variable: "CurFunc", Field: "Typecheck.IR.CurFunc"},
		},
	}
	for _, group := range []struct {
		file, prefix string
		names        []string
	}{
		{"ir/expr.go", "Typecheck.IR.", []string{"NewBasicLit", "NewBinaryExpr", "NewCallExpr", "NewConvExpr", "NewStarExpr"}},
		{"ir/stmt.go", "Typecheck.IR.", []string{"NewAssignStmt", "NewBranchStmt", "NewForStmt", "NewIfStmt", "NewLabelStmt", "NewReturnStmt"}},
		{"ir/const.go", "Typecheck.IR.", []string{"NewBool", "NewInt"}},
		{"ir/func.go", "Typecheck.IR.", []string{"NewFunc", "WithFunc"}},
		{"ir/fmt.go", "Typecheck.IR.", []string{"DumpList"}},
		{"types/type.go", "Typecheck.IR.Types.", []string{"NewField", "NewSignature"}},
		{"types/alg.go", "Typecheck.IR.Types.", []string{"AlgType"}},
		{"typecheck/syms.go", "Typecheck.", []string{"Lookup", "LookupRuntime", "LookupRuntimeFunc", "LookupRuntimeVar", "AutoLabel"}},
		{"typecheck/dcl.go", "Typecheck.", []string{"DeclFunc", "FinishFuncBody", "TempAt"}},
		{"typecheck/typecheck.go", "Typecheck.", []string{"Call", "Stmts"}},
		{"objw/objw.go", "Runtime.Writer.", []string{"SymPtr", "Uintptr"}},
	} {
		for _, name := range group.names {
			u.Calls = append(u.Calls, CallRule{Source: "src/cmd/compile/internal/" + group.file, Function: name, Method: group.prefix + name})
		}
	}
	return u
}
